def main():
    english = {}
    order = []
    for line in open(os.path.join(TRANSLATIONS, 'ModernCameraCollision_ENGLISH.txt'), encoding='utf-16').read().split('\n'):
        line = line.rstrip('\r')
        if '\t' in line:
            k, v = line.split('\t', 1)
            english[k] = v
            order.append(k)
    for language, strings in T.items():
        strings = dict(strings)
        for layer in ('L_STATIC', 'L_ANIMSTATIC', 'L_TREES', 'L_TERRAIN', 'L_GROUND'):
            strings[f'$MCC_iL_{layer[2:]}'] = layer
            strings[f'$MCC_iL_{layer[2:]}_Help'] = LAYER_HELP[language] + (TREES_EXTRA[language] if layer == 'L_TREES' else '')
        missing = [k for k in order if k not in strings]
        if missing:
            print(language, 'missing, kept English:', missing)
        text = ''.join(f'{k}\t{strings.get(k, english[k])}\r\n' for k in order)
        with open(os.path.join(TRANSLATIONS, f'ModernCameraCollision_{language}.txt'), 'wb') as f:
            f.write(b'\xff\xfe' + text.encode('utf-16-le'))
        print(language, len(order))


if __name__ == '__main__':
    main()
